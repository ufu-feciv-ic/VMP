inline PerfilI criar_perfil_do_catalogo(const InfoPerfilCatalogo& info) {
    PerfilI p;
    p.nome = info.nome;
    p.tipo = info.tipo;
    p.d = info.d_mm;
    p.bf = info.bf_mm;
    p.tw = info.tw_mm;
    p.tf = info.tf_mm;
    p.h = p.d - 2.0 * p.tf;
    p.d1 = p.h;
    p.Ix = info.Ix_cm4 * 1e4;
    p.Wx = info.Wx_cm3 * 1e3;
    p.Zx = info.Zx_cm3 * 1e3;
    p.Iy = info.Iy_cm4 * 1e4;
    p.Ag = (2.0 * p.bf * p.tf + p.h * p.tw);
    if (p.Ag > 0.0) {
        p.rx = std::sqrt(p.Ix / p.Ag);
        p.ry = std::sqrt(p.Iy / p.Ag);
    }
    if (p.tf > 0.0) p.lbf = p.bf / (2.0 * p.tf);
    if (p.tw > 0.0) p.lbw = p.d1 / p.tw;
    if (p.bf > 0.0) p.Wy = p.Iy / (p.bf / 2.0);
    p.Zy = (p.tf * p.bf * p.bf / 2.0) + (p.h * p.tw * p.tw / 4.0);
    p.It = (2.0 * p.bf * std::pow(p.tf, 3.0) + p.h * std::pow(p.tw, 3.0)) / 3.0;
    p.Cw = (p.tf * std::pow(p.bf, 3.0) * std::pow(p.d - p.tf, 2.0)) / 24.0;
    if (p.bf > 0.0 && p.tf > 0.0) {
        p.rt = p.bf / std::sqrt(12.0 * (1.0 + (p.h * p.tw) / (6.0 * p.bf * p.tf)));
    }
    return p;
}

